#!/usr/bin/env python3
"""
ARUNA Pipeline Diagnostic Runner -- X6.3 (2024-02-22).

Runs every stage explicitly, labels each output:
  REAL      -- computed from real PRADAN FITS data
  SYNTHETIC -- generated by the fallback profile
  DEGRADED  -- real data used but model/catalog missing (physics heuristic applied)
  FAILED    -- stage threw an exception

Usage:
    python python/scripts/run_diagnostic.py
    python python/scripts/run_diagnostic.py --fits-dir data/solexs_20240222/ --single-instrument
    python python/scripts/run_diagnostic.py --output data/x63_report.json
"""
from __future__ import annotations

import argparse
import json
import logging
import sys
import time
import traceback
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

logging.basicConfig(level=logging.WARNING, format="%(levelname)-8s %(name)s - %(message)s")
logger = logging.getLogger("aruna.diagnostic")

sys.path.insert(0, str(Path(__file__).parent.parent))

from aruna.pipeline.run import (
    _find_fits,
    _make_synthetic_physics_frames,
    _synthetic_forecast,
    _synthetic_nowcast,
    run_l1_pradan,
    run_l2,
    run_l3,
    run_l4,
    run_l5,
    run_l6,
    run_l7,
)


@dataclass
class StageResult:
    stage: str
    status: str
    n_outputs: int = 0
    key_metrics: Dict[str, Any] = field(default_factory=dict)
    errors: List[str] = field(default_factory=list)
    elapsed_sec: float = 0.0
    notes: str = ""


STATUS_ICONS = {
    "REAL":      "OK  REAL   ",
    "SYNTHETIC": "~~  SYNTH  ",
    "DEGRADED":  "!!  DEGRD  ",
    "FAILED":    "XX  FAIL   ",
    "SKIPPED":   "--  SKIP   ",
}


def _fmt(val, fmt=".3g") -> str:
    try:
        return format(float(val), fmt)
    except Exception:
        return str(val)


def run_diagnostic(
    fits_dir: str,
    single_instrument: bool = False,
    window_sec: int = 5400,
    output: Optional[str] = None,
) -> List[StageResult]:
    results: List[StageResult] = []
    t_total = time.monotonic()

    print()
    print("=" * 72)
    print(f"  ARUNA PIPELINE DIAGNOSTIC  --  {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}")
    print(f"  Event  : X6.3 (2024-02-22 22:32:34 UTC)")
    print(f"  Source : {fits_dir}")
    print(f"  Flags  : single_instrument={single_instrument}  window_sec={window_sec}")
    print("=" * 72)

    # --- L0: FITS discovery --------------------------------------------------
    t0 = time.monotonic()
    fits_files: dict = {}
    l0_notes = ""
    l0_status = "FAILED"
    try:
        fits_dir_path = Path(fits_dir)
        if fits_dir_path.exists():
            fits_files = _find_fits(fits_dir_path)
        n_solexs_pi = len(fits_files.get("solexs_pi", []))
        n_hel1os_pi = len(fits_files.get("hel1os_pi", []))
        l0_status = "REAL" if n_solexs_pi > 0 else "FAILED"
        if n_solexs_pi == 0:
            l0_notes = "No SoLEXS PI files found -- check path and file names"
        elif n_hel1os_pi == 0:
            l0_notes = "No HEL1OS PI files -- proxy will be synthesized"
    except Exception as exc:
        l0_status = "FAILED"
        l0_notes = str(exc)

    results.append(StageResult(
        stage="L0 FITS Discovery",
        status=l0_status,
        n_outputs=len(fits_files.get("all", [])),
        key_metrics={
            "solexs_pi": len(fits_files.get("solexs_pi", [])),
            "hel1os_pi": len(fits_files.get("hel1os_pi", [])),
            "hk_files":  len(fits_files.get("hk", [])),
        },
        elapsed_sec=time.monotonic() - t0,
        notes=l0_notes,
    ))

    # --- L1: Ingestion -------------------------------------------------------
    t0 = time.monotonic()
    obs_frames: List = []
    l1_status = "FAILED"
    l1_notes = ""
    try:
        if fits_files.get("solexs_pi"):
            obs_frames = run_l1_pradan(
                fits_files,
                single_instrument=single_instrument,
                window_sec=window_sec,
            )
            n_real  = sum(1 for f in obs_frames if not getattr(f, 'source_file', '').startswith("PROXY:"))
            n_stix  = sum(1 for f in obs_frames if getattr(f, 'source_file', '').startswith("STIX:"))
            n_proxy = sum(1 for f in obs_frames if getattr(f, 'source_file', '').startswith("PROXY:"))
            l1_status = "REAL" if n_real > 0 else "FAILED"
            if n_stix > 0:
                l1_notes = f"{n_stix} HEL1OS frames from Solar Orbiter/STIX (distance-corrected)"
            elif n_proxy > 0:
                l1_notes = f"{n_proxy} HEL1OS proxy frames synthesized from SoLEXS"
        else:
            l1_status = "FAILED"
            l1_notes = "No PRADAN PI files found -- cannot ingest real data"
    except Exception as exc:
        l1_status = "FAILED"
        l1_notes = traceback.format_exc(limit=4)
        logger.error("L1 failed: %s", exc)

    results.append(StageResult(
        stage="L1 Ingestion",
        status=l1_status,
        n_outputs=len(obs_frames),
        key_metrics={
            "real_frames":  sum(1 for f in obs_frames if not getattr(f, 'source_file', '').startswith(("PROXY:", "STIX:"))),
            "stix_frames":  sum(1 for f in obs_frames if getattr(f, 'source_file', '').startswith("STIX:")),
            "proxy_frames": sum(1 for f in obs_frames if getattr(f, 'source_file', '').startswith("PROXY:")),
        },
        elapsed_sec=time.monotonic() - t0,
        notes=l1_notes,
    ))

    # --- L2: Physics ---------------------------------------------------------
    t0 = time.monotonic()
    physics_frames: List = []
    l2_status = "FAILED"
    l2_notes = ""
    try:
        if obs_frames:
            physics_frames = run_l2(obs_frames)
            l2_status = "REAL" if physics_frames else "FAILED"
            l2_notes = "" if physics_frames else "L2 produced no frames"
    except Exception as exc:
        l2_status = "FAILED"
        l2_notes = str(exc)
        logger.error("L2 failed: %s", exc)

    if not physics_frames:
        physics_frames = _make_synthetic_physics_frames(300)
        l2_status = "SYNTHETIC"
        if not l2_notes:
            l2_notes = "Using synthetic X6.3 profile (L1 produced no frames)"

    hope_frames = [pf for pf in physics_frames if getattr(pf, "hope_flag", False)]
    peak_T   = max((getattr(pf, "T_MK", 0) for pf in physics_frames), default=0)
    peak_DNI = max((getattr(pf, "DNI", 0) for pf in physics_frames), default=0)

    results.append(StageResult(
        stage="L2 Physics",
        status=l2_status,
        n_outputs=len(physics_frames),
        key_metrics={
            "hope_frames": len(hope_frames),
            "peak_T_MK":   _fmt(peak_T),
            "peak_DNI":    _fmt(peak_DNI),
        },
        elapsed_sec=time.monotonic() - t0,
        notes=l2_notes,
    ))

    # --- L3: Nowcasting ------------------------------------------------------
    t0 = time.monotonic()
    nowcast_event = None
    l3_status = "FAILED"
    l3_notes = ""
    try:
        nowcast_event, _ = run_l3(physics_frames)
        if nowcast_event:
            has_stix = any(
                getattr(f, 'source_file', '').startswith("STIX:")
                for f in obs_frames
            )
            det = getattr(nowcast_event, 'detection_method', '')
            if det == "DUAL_TRIGGER":
                l3_status = "REAL" if not has_stix else "DEGRADED"
                if has_stix:
                    l3_notes = "Dual-trigger via SoLEXS + Solar Orbiter/STIX (STIX replaces HEL1OS)"
            elif det == "SOLEXS_ONLY":
                l3_status = "DEGRADED"
                l3_notes = "SoLEXS-only trigger (HEL1OS/STIX did not meet threshold)"
            elif det == "HOPE":
                l3_status = "DEGRADED"
                l3_notes = "HOPE precursor only (no confirmed onset yet)"
            else:
                l3_status = "REAL"
        else:
            l3_status = "SYNTHETIC"
            l3_notes = "No event detected -- dual-trigger failed; synthetic injected"
            nowcast_event = _synthetic_nowcast("X", 6.3)
    except Exception as exc:
        l3_status = "FAILED"
        l3_notes = str(exc)
        nowcast_event = _synthetic_nowcast("X", 6.3)
        logger.error("L3 failed: %s", exc)

    results.append(StageResult(
        stage="L3 Nowcasting",
        status=l3_status,
        n_outputs=1 if nowcast_event else 0,
        key_metrics={
            "goes_label":  getattr(nowcast_event, "goes_label", "N/A"),
            "confidence":  _fmt(getattr(nowcast_event, "confidence", 0)),
            "lead_time_s": getattr(nowcast_event, "lead_time_sec", "N/A"),
            "instruments": str(getattr(nowcast_event, "instruments", [])),
        },
        elapsed_sec=time.monotonic() - t0,
        notes=l3_notes,
    ))

    # --- L4: Forecasting -----------------------------------------------------
    t0 = time.monotonic()
    forecast_frames: List = []
    l4_status = "FAILED"
    l4_notes = ""
    try:
        forecast_frames = run_l4(physics_frames, nowcast_event) or []
        if forecast_frames:
            ff = forecast_frames[0]
            probs = [ff.prob_quiet, ff.prob_B, ff.prob_C, ff.prob_M, ff.prob_X]
            is_uniform = all(abs(p - 0.2) < 0.01 for p in probs)
            if is_uniform:
                l4_status = "FAILED"
                l4_notes = "Uniform probabilities -- TCN AND physics heuristic both failed"
            else:
                l4_status = "DEGRADED"
                l4_notes = "Physics heuristic applied (no trained TCN/Moirai model)"
        else:
            forecast_frames = [_synthetic_forecast()]
            l4_status = "SYNTHETIC"
            l4_notes = "Buffer not full -- synthetic ForecastFrame injected"
    except Exception as exc:
        forecast_frames = [_synthetic_forecast()]
        l4_status = "FAILED"
        l4_notes = str(exc)
        logger.error("L4 failed: %s", exc)

    ff = forecast_frames[0] if forecast_frames else None
    results.append(StageResult(
        stage="L4 Forecasting",
        status=l4_status,
        n_outputs=len(forecast_frames),
        key_metrics={
            "class":   getattr(ff, "predicted_class", "N/A"),
            "P(M+X)":  _fmt(getattr(ff, "prob_M", 0) + getattr(ff, "prob_X", 0)),
            "P(X)":    _fmt(getattr(ff, "prob_X", 0)),
            "lead_s":  getattr(ff, "lead_time_estimate_sec", "N/A"),
        },
        elapsed_sec=time.monotonic() - t0,
        notes=l4_notes,
    ))

    # --- L5: Analogs ---------------------------------------------------------
    t0 = time.monotonic()
    analogs: List = []
    l5_status = "FAILED"
    l5_notes = ""
    try:
        from aruna.l5_analogs.models import NO_ANALOG
        analogs = run_l5(forecast_frames, physics_frames)
        if analogs and analogs[0] is not NO_ANALOG:
            l5_status = "REAL"
        else:
            l5_status = "DEGRADED"
            l5_notes = "Catalog empty -- NO_ANALOG (expected on first run)"
    except Exception as exc:
        l5_status = "FAILED"
        l5_notes = str(exc)
        logger.error("L5 failed: %s", exc)

    results.append(StageResult(
        stage="L5 Analogs",
        status=l5_status,
        n_outputs=sum(1 for a in analogs if getattr(a, "event_id", None)),
        key_metrics={
            "top_analog": getattr(analogs[0], "event_id", "NO_ANALOG") if analogs else "N/A",
        },
        elapsed_sec=time.monotonic() - t0,
        notes=l5_notes,
    ))

    # --- L6: Threat ----------------------------------------------------------
    t0 = time.monotonic()
    threat = None
    l6_status = "FAILED"
    l6_notes = ""
    try:
        threat = run_l6(nowcast_event)
        l6_status = "REAL" if threat else "FAILED"
        if not threat:
            l6_notes = "ThreatOrchestrator returned None"
    except Exception as exc:
        l6_status = "FAILED"
        l6_notes = str(exc)
        logger.error("L6 failed: %s", exc)

    results.append(StageResult(
        stage="L6 Threat",
        status=l6_status,
        n_outputs=1 if threat else 0,
        key_metrics={
            "navic_worst": str(max(threat.navic_risk.values(), default="N/A")) if threat else "N/A",
            "hf_risk":     getattr(threat, "hf_risk", "N/A"),
            "gaganyaan":   getattr(threat, "gaganyaan_advisory", "N/A"),
        },
        elapsed_sec=time.monotonic() - t0,
        notes=l6_notes,
    ))

    # --- L7: Briefing --------------------------------------------------------
    t0 = time.monotonic()
    briefing = None
    l7_status = "FAILED"
    l7_notes = ""
    if threat:
        try:
            briefing = run_l7(nowcast_event, forecast_frames, threat, analogs, provider="mock")
            l7_status = "REAL"
        except Exception as exc:
            l7_status = "FAILED"
            l7_notes = str(exc)
            logger.error("L7 failed: %s", exc)
    else:
        l7_status = "SKIPPED"
        l7_notes = "Skipped: L6 threat output unavailable"

    results.append(StageResult(
        stage="L7 LLM Briefing",
        status=l7_status,
        n_outputs=1 if briefing else 0,
        key_metrics={
            "source":     getattr(briefing, "briefing_source", "N/A"),
            "violations": len(getattr(briefing, "hallucination_violations", [])),
        },
        elapsed_sec=time.monotonic() - t0,
        notes=l7_notes,
    ))

    # --- Print Report --------------------------------------------------------
    total_elapsed = time.monotonic() - t_total
    print()
    print(f"  {'Stage':<22}  {'Status':<14}  {'N':>6}  Key Metrics")
    print("  " + "-" * 68)
    for r in results:
        icon    = STATUS_ICONS.get(r.status, r.status.ljust(12))
        metrics = "  ".join(f"{k}={v}" for k, v in list(r.key_metrics.items())[:4])
        print(f"  {r.stage:<22}  {icon}  {r.n_outputs:>6}  {metrics}")
        if r.notes:
            print(f"  {'':22}  {'':14}         NOTE: {r.notes}")

    print("  " + "-" * 68)
    n_real   = sum(1 for r in results if r.status == "REAL")
    n_synth  = sum(1 for r in results if r.status == "SYNTHETIC")
    n_degrad = sum(1 for r in results if r.status == "DEGRADED")
    n_failed = sum(1 for r in results if r.status == "FAILED")
    print(f"\n  SUMMARY: {n_real} REAL  {n_synth} SYNTHETIC  {n_degrad} DEGRADED  {n_failed} FAILED")
    print(f"  Total elapsed: {total_elapsed:.1f}s")

    if briefing:
        print()
        print("=" * 72)
        print("  PIPELINE OUTPUT -- LLM BRIEFING")
        print("=" * 72)
        print(briefing.briefing_text)
        if briefing.hallucination_violations:
            print(f"\n  [Guard violations: {briefing.hallucination_violations}]")

    # --- JSON report ---------------------------------------------------------
    if output:
        report = {
            "event_id":          "SOL2024-02-22-X6.3",
            "run_at":            datetime.now(timezone.utc).isoformat(),
            "fits_dir":          fits_dir,
            "single_instrument": single_instrument,
            "window_sec":        window_sec,
            "total_elapsed_sec": round(total_elapsed, 2),
            "stages": [
                {
                    "stage":       r.stage,
                    "status":      r.status,
                    "n_outputs":   r.n_outputs,
                    "key_metrics": r.key_metrics,
                    "errors":      r.errors,
                    "elapsed_sec": round(r.elapsed_sec, 3),
                    "notes":       r.notes,
                }
                for r in results
            ],
        }
        if briefing:
            report["briefing_text"]   = briefing.briefing_text
            report["briefing_source"] = briefing.briefing_source
        if nowcast_event:
            report["nowcast"] = {
                "goes_label":  getattr(nowcast_event, "goes_label", "N/A"),
                "confidence":  getattr(nowcast_event, "confidence", None),
                "lead_time_s": getattr(nowcast_event, "lead_time_sec", None),
                "instruments": getattr(nowcast_event, "instruments", []),
            }
        if ff:
            report["forecast"] = {
                "predicted_class": getattr(ff, "predicted_class", "N/A"),
                "prob_quiet": getattr(ff, "prob_quiet", None),
                "prob_B":     getattr(ff, "prob_B", None),
                "prob_C":     getattr(ff, "prob_C", None),
                "prob_M":     getattr(ff, "prob_M", None),
                "prob_X":     getattr(ff, "prob_X", None),
            }
        if threat:
            report["threat"] = {
                "navic_risk": getattr(threat, "navic_risk", {}),
                "hf_risk":    getattr(threat, "hf_risk", "N/A"),
                "gaganyaan":  getattr(threat, "gaganyaan_advisory", "N/A"),
            }

        out_path = Path(output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
        print(f"\n  Diagnostic report written to: {output}")

    print()
    return results


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="ARUNA diagnostic pipeline runner -- X6.3 2024-02-22",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--fits-dir", default="data/solexs_20240222/",
                        help="Directory with PRADAN FITS files")
    parser.add_argument("--single-instrument", action="store_true",
                        help="Synthesize HEL1OS proxy from SoLEXS when HEL1OS data absent")
    parser.add_argument("--window-sec", type=int, default=5400,
                        help="Time window around X6.3 peak in seconds (default 5400 = 90 min)")
    parser.add_argument("--output", default="data/x63_diagnostic_report.json",
                        help="Write JSON report to this file")
    args = parser.parse_args()

    run_diagnostic(
        fits_dir=args.fits_dir,
        single_instrument=args.single_instrument,
        window_sec=args.window_sec,
        output=args.output,
    )
